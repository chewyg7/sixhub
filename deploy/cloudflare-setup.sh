#!/usr/bin/env bash
# Puts GTA 6 Hub's nginx site behind Cloudflare. Run as root, AFTER the DNS
# records are proxied (orange cloud) and the Cloudflare Origin Certificate is
# saved (see DEPLOY.md, "Cloudflare"). Safe to re-run (refreshes Cloudflare's
# IP list); keeps a backup of the previous site file and restores it if the
# new config doesn't pass `nginx -t`.
#
#   sudo bash /srv/gtasixhub/deploy/cloudflare-setup.sh             # nginx only
#   sudo bash /srv/gtasixhub/deploy/cloudflare-setup.sh --firewall  # also lock ports 80/443 to Cloudflare (ufw)
#
# --firewall affects EVERY site on this server: only use it if all of them are
# behind Cloudflare. Without it, nginx still refuses gtasixhub.com requests that
# didn't come through Cloudflare.
set -euo pipefail

APP=/srv/gtasixhub
SITE=/etc/nginx/sites-available/gtasixhub
CERT=/etc/ssl/cloudflare/gtasixhub.com.pem
KEY=/etc/ssl/cloudflare/gtasixhub.com.key
FIREWALL=0
[[ "${1:-}" == "--firewall" ]] && FIREWALL=1

[[ $EUID -eq 0 ]] || { echo "Run as root (sudo)."; exit 1; }
if [[ ! -s $CERT || ! -s $KEY ]]; then
  echo "Missing the Cloudflare Origin Certificate."
  echo "Create it in Cloudflare (SSL/TLS > Origin Server > Create Certificate) and save it as:"
  echo "  $CERT   (certificate)"
  echo "  $KEY    (private key, chmod 600)"
  exit 1
fi

echo "1/5  Fetching Cloudflare's IP ranges…"
V4=$(curl -fsS https://www.cloudflare.com/ips-v4)
V6=$(curl -fsS https://www.cloudflare.com/ips-v6)
RANGES=$(printf "%s\n%s\n" "$V4" "$V6" | grep -E '^[0-9a-fA-F:.]+/[0-9]+$')
[[ $(echo "$RANGES" | wc -l) -gt 10 ]] || { echo "Couldn't get Cloudflare's IP list."; exit 1; }

# The Origin Certificate is only trusted by Cloudflare, so the domain must already
# point at Cloudflare (orange cloud) or visitors would get certificate errors.
SERVED_BY_CF=$(python3 - "$RANGES" <<'PY'
import ipaddress, socket, sys
nets = [ipaddress.ip_network(r) for r in sys.argv[1].split()]
try:
    addrs = {a[4][0] for a in socket.getaddrinfo("gtasixhub.com", 443)}
except OSError:
    addrs = set()
print(1 if addrs and all(any(ipaddress.ip_address(a) in n for n in nets) for a in addrs) else 0)
PY
)
if [[ $SERVED_BY_CF != 1 ]]; then
  echo "gtasixhub.com doesn't point at Cloudflare yet. Set the gtasixhub.com and www records to"
  echo "Proxied (orange cloud) in Cloudflare, wait a minute, then run this again. Nothing was changed."
  exit 1
fi

echo "2/5  Writing nginx snippets…"
mkdir -p /etc/nginx/snippets
{
  echo "# Cloudflare edge addresses: trust their CF-Connecting-IP header for the visitor's real IP."
  echo "# Generated by deploy/cloudflare-setup.sh on $(date -u +%F)."
  while read -r r; do echo "set_real_ip_from $r;"; done <<< "$RANGES"
  echo "real_ip_header CF-Connecting-IP;"
} > /etc/nginx/snippets/cloudflare-real-ip.conf
{
  echo "# 1 when the connection comes from Cloudflare (checked against the address that actually connected)."
  echo "# Generated by deploy/cloudflare-setup.sh on $(date -u +%F)."
  echo "geo \$realip_remote_addr \$from_cloudflare {"
  echo "    default 0;"
  while read -r r; do echo "    $r 1;"; done <<< "$RANGES"
  echo "}"
} > /etc/nginx/conf.d/cloudflare-geo.conf
cp "$APP/deploy/nginx-gtasixhub-proxy.conf" /etc/nginx/snippets/gtasixhub-proxy.conf
# Refuse gtasixhub.com requests that didn't come through Cloudflare (someone hitting the server's IP).
echo 'if ($from_cloudflare = 0) { return 444; }' > /etc/nginx/snippets/gtasixhub-cloudflare-only.conf

echo "3/5  Installing the site config…"
BACKUP=""
if [[ -f $SITE ]]; then BACKUP="$SITE.bak-$(date +%Y%m%d-%H%M%S)"; cp "$SITE" "$BACKUP"; fi
cp "$APP/deploy/nginx-gtasixhub.conf" "$SITE"
ln -sf "$SITE" /etc/nginx/sites-enabled/gtasixhub

echo "4/5  Testing nginx…"
if ! nginx -t; then
  echo "nginx rejected the new config; putting the previous one back."
  [[ -n $BACKUP ]] && cp "$BACKUP" "$SITE"
  rm -f /etc/nginx/conf.d/cloudflare-geo.conf
  nginx -t && systemctl reload nginx
  exit 1
fi
systemctl reload nginx
# nginx serves /public itself now, so it must be able to read it.
if ! sudo -u www-data test -r "$APP/public/brand/logo-480.webp"; then
  echo "     WARNING: nginx (www-data) can't read $APP/public; images will fall back to the app."
  echo "              Fix with: chmod o+rx /srv $APP $APP/public && chmod -R o+rX $APP/public $APP/.next/static"
fi

if [[ $FIREWALL == 1 ]]; then
  echo "5/5  Locking ports 80/443 to Cloudflare (ufw)…"
  ufw allow OpenSSH >/dev/null
  while read -r r; do ufw allow proto tcp from "$r" to any port 80,443 comment "cloudflare" >/dev/null; done <<< "$RANGES"
  for rule in "80,443/tcp" "80/tcp" "443/tcp" "Nginx Full" "Nginx HTTP" "Nginx HTTPS"; do ufw delete allow "$rule" >/dev/null 2>&1 || true; done
  ufw --force enable >/dev/null
  ufw status | head -5
else
  echo "5/5  Firewall left as is (run with --firewall to lock ports 80/443 to Cloudflare for the whole server)."
fi

echo "Done. Check: curl -sI https://gtasixhub.com | grep -i -E 'server|cf-ray'"
