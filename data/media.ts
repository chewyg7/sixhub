import type { ISODate, MediaCategorySlug, Verification } from "@/types/content";

/**
 * Editorial media records.
 *
 * A record holds everything a human editor writes about a file: title,
 * description, relationships and dates. Technical data (dimensions, file
 * sizes, codecs, variants, storyboards) is produced by the ingest pipeline
 * — here `scripts/generate-sample-assets.mjs`, which writes
 * `data/generated/sample-assets.json`. `lib/content/local-source.ts` joins
 * the two into `MediaItem`s.
 *
 * DEVELOPMENT DATASET: every file referenced below is a procedurally
 * generated, watermarked stand-in (`verification: "sample"`). Replace the
 * records and assets with official media before launch.
 */
export interface MediaRecord {
  slug: string;
  title: string;
  category: MediaCategorySlug;
  description: string;
  alt: string;
  datePublished: ISODate;
  dateAdded: ISODate;
  source: string;
  officialUrl?: string;
  tags: string[];
  characters: string[];
  locations: string[];
  downloadable: boolean;
  credit?: string;
  verification: Verification;
}

